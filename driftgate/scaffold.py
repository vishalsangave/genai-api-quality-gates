START_SERVICE_STEP = """
      - name: Start service under test
        run: |
          {command} > /tmp/driftgate-service.log 2>&1 &
          echo $! > /tmp/driftgate-service.pid
"""


def workflow_source(start_service_command: str | None) -> str:
    step = ""
    if start_service_command:
        step = START_SERVICE_STEP.format(command=start_service_command)
    return WORKFLOW_TEMPLATE.format(start_service_step=step)


def write_if_absent(path: Path, content: str, written: list[Path], skipped: list[Path]) -> None:
    if path.exists():
        skipped.append(path)
        return
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content)
    written.append(path)


def ensure_gitignore_entries(root: Path) -> bool:
    gitignore = root / ".gitignore"
    entries = [".driftgate/", "cassettes/"]
    existing = gitignore.read_text().splitlines() if gitignore.exists() else []
    missing = [entry for entry in entries if entry not in existing]
    if not missing:
        return False
    with gitignore.open("a") as handle:
        handle.write("\n# DriftGate artifacts\n" + "\n".join(missing) + "\n")
    return True


def load_spec_if_present(spec_path: str | None) -> dict | None:
    if not spec_path:
        return None
    path = Path(spec_path)
    if not path.exists():
        return None
    loaded = yaml.safe_load(path.read_text())
    return loaded if isinstance(loaded, dict) else None
