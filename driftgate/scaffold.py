PROBE_CANDIDATES = ("/healthz", "/health", "/")


def probe_path(spec: dict | None) -> str:
    """Pick the readiness path: a spec-declared GET without params, else /healthz."""
    if spec:
        for template, path_item in spec.get("paths", {}).items():
            if "{" not in template:
                definition = path_item.get("get")
                if isinstance(definition, dict) and "200" in definition.get("responses", {}):
                    return template
    return "/healthz"


def _example_value(schema: dict) -> str:
    if "enum" in schema and schema["enum"]:
        return repr(schema["enum"][0])
    example = schema.get("example")
    if example is not None:
        return repr(example)
    if "default" in schema:
        return repr(schema["default"])
    kind = schema.get("type", "string")
    if kind == "integer":
        return "1"
    if kind == "number":
        return "1.0"
    if kind == "boolean":
        return "True"
    if kind == "array":
        return "[]"
    if kind == "object":
        return "{}"
    return '"driftgate"'


def _request_body_expr(operation: dict) -> str | None:
    content = operation.get("requestBody", {}).get("content", {})
    schema = (
        content.get("application/json", {}).get("schema") if isinstance(content, dict) else None
    )
    if not isinstance(schema, dict):
        return None
    if schema.get("type") == "object" or "properties" in schema:
        properties = schema.get("properties", {})
        required = schema.get("required", [])
        # Dict literal, not keyword args: JSON keys may not be Python identifiers.
        fields = ", ".join(
            f"{_py_key(name)}: {_example_value(properties[name])}" for name in required
        )
        return "{" + fields + "}"
    return _example_value(schema)


def _py_key(name: str) -> str:
    return name if re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", name) else repr(name)


def _sentinel_for_param(param_name: str) -> str:
    lowered = param_name.lower()
    if "id" in lowered:
        return "00000"
    return "driftgate-probe"


def _spec_operation_tests(spec: dict) -> str:
    lines: list[str] = []
    for template, path_item in sorted(spec.get("paths", {}).items()):
        for method, operation in sorted(path_item.items()):
            if method not in {"get", "post", "put", "patch", "delete"}:
                continue
            if not isinstance(operation, dict):
                continue
            test_name = _test_name(method, template)
            path_expr = template
            params = operation.get("parameters", [])
            if isinstance(params, list) and any(
                p.get("in") == "path" for p in params if isinstance(p, dict)
            ):
                concrete = template
                for param in params:
                    if isinstance(p := param, dict) and p.get("in") == "path":
                        concrete = concrete.replace(
                            "{" + p["name"] + "}", _sentinel_for_param(p["name"])
                        )
                path_expr = repr(concrete)
                lines.append(
                    f"""

def test_{test_name}(driftgate_client: httpx.Client) -> None:
    # Probe with a non-existent sentinel; 404-or-2xx both prove the route lives.
    response = driftgate_client.request({method.upper()!r}, {path_expr})
    assert response.status_code < 500
"""
                )
                continue
            body_expr = (
                _request_body_expr(operation) if method in {"post", "put", "patch"} else None
            )
            if body_expr:
                body = f", json={body_expr}"
            else:
                body = ""
            path_literal = repr(template)
            lines.append(
                f"""

def test_{test_name}(driftgate_client: httpx.Client) -> None:
    response = driftgate_client.request({method.upper()!r}, {path_literal}{body})
    assert response.status_code < 500
"""
            )
    return "".join(lines)


def _test_name(method: str, template: str) -> str:
    slug = re.sub(r"[^A-Za-z0-9]+", "_", template).strip("_").lower()
    return f"{method}_{slug}_responds"


def starter_test_source(base_url: str, spec: dict | None) -> str:
    extra = _spec_operation_tests(spec) if spec else ""
    return STARTER_TEST_TEMPLATE.format(probe_path=probe_path(spec), extra_tests=extra)


